enum { M_NONE, M_ACUTE, M_UML, M_DACUTE };
typedef struct { uint16_t cp; char base; uint8_t mark; } acc_t;
static const acc_t ACC[] = {
    { 0xC1, 'A', M_ACUTE }, { 0xC9, 'E', M_ACUTE }, { 0xCD, 'I', M_ACUTE }, { 0xD3, 'O', M_ACUTE }, { 0xD6, 'O', M_UML },
    { 0x150, 'O', M_DACUTE }, { 0xDA, 'U', M_ACUTE }, { 0xDC, 'U', M_UML }, { 0x170, 'U', M_DACUTE },
    { 0xE1, 'a', M_ACUTE }, { 0xE9, 'e', M_ACUTE }, { 0xED, 'i', M_ACUTE }, { 0xF3, 'o', M_ACUTE }, { 0xF6, 'o', M_UML },
    { 0x151, 'o', M_DACUTE }, { 0xFA, 'u', M_ACUTE }, { 0xFC, 'u', M_UML }, { 0x171, 'u', M_DACUTE },
};
int font_glyph(uint32_t cp, uint16_t cols[5]) {
    int mark = M_NONE;
    if (cp > 126) {
        int found = 0;
        for (size_t i = 0; i < sizeof ACC / sizeof ACC[0]; i++)
            if (ACC[i].cp == cp) { cp = (uint8_t)ACC[i].base; mark = ACC[i].mark; found = 1; break; }
        if (!found) return 0;
    }
    if (cp < 32 || cp > 126) return 0;
    for (int i = 0; i < 5; i++) cols[i] = (uint16_t)F[cp - 32][i] << 2;
    if (mark && cp == 'i') cols[2] &= (uint16_t)~(1 << 2);   /* the dotless i under an accent */
    switch (mark) {
    case M_ACUTE:  cols[2] |= 0x02; cols[3] |= 0x01; break;
    case M_UML:    cols[1] |= 0x03; cols[3] |= 0x03; break;
    case M_DACUTE: cols[1] |= 0x02; cols[2] |= 0x01; cols[3] |= 0x02; cols[4] |= 0x01; break;
    default: break;
    }
    return 1;
}
