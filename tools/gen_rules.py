#!/usr/bin/env python3
"""Pixel Lili: the teacher's rules from model/teacher_rules.yaml into C (spec 10.7).

    py -3.12 tools/gen_rules.py

Each template's condition and score (Python-syntax expressions over the brain's input fields) become small C
functions over the brain state f[] (common/lili/schema_gen.h's F_* fields and V_* values); its plan's slots become
action lists. Out: common/lili/brain_rules_gen.c. A name the schema does not know is an error here, not a silent
zero on the panel.
"""
import ast, json, os, sys
import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCHEMA = json.load(open(os.path.join(ROOT, "model", "schema_lili.json"), encoding="utf-8"))
FIELDS = {f["field"]: f for f in SCHEMA["input"]}
ACTS = [a for g in SCHEMA["classes"]["act"].values() for a in g]
STYLES = [t[3:] for t in SCHEMA["classes"]["st"]]
FACES = [t[3:] for t in SCHEMA["classes"]["fc"]]
BUBBLES = [t[3:] for t in SCHEMA["classes"]["bb"]]
KINDS = ["play", "rest", "eat", "explore", "greet", "mischief", "social", "none"]   # = model/schema_lili.json "last" order
FUNCS = {"min": "fminf", "max": "fmaxf", "log": "logf", "exp": "expf"}

class Err(Exception): pass

def value_of(field, name):
    """a bare token name compared with a field -> its V_ constant (or its number for bucket fields)"""
    f = FIELDS[field]
    if "tokens" not in f: raise Err(f"{field} is a number (0..{f['buckets'] - 1}), not a token: {name}")
    tok = f"{field}_{name}"
    if tok not in f["tokens"]: raise Err(f"{field} has no value {name!r} (it has {', '.join(t[len(field) + 1:] for t in f['tokens'])})")
    return f"V_{tok.upper()}"

def emit(node, ctx_field=None):
    if isinstance(node, ast.Expression): return emit(node.body)
    if isinstance(node, ast.BoolOp):
        op = " && " if isinstance(node.op, ast.And) else " || "
        return "(" + op.join(emit(v) for v in node.values) + ")"
    if isinstance(node, ast.UnaryOp):
        if isinstance(node.op, ast.Not): return f"(!{emit(node.operand)})"
        if isinstance(node.op, ast.USub): return f"(-{emit(node.operand)})"
    if isinstance(node, ast.BinOp):
        ops = {ast.Add: "+", ast.Sub: "-", ast.Mult: "*", ast.Div: "/"}
        if type(node.op) not in ops: raise Err(f"operator {type(node.op).__name__}")
        return f"({emit(node.left)} {ops[type(node.op)]} {emit(node.right)})"
    if isinstance(node, ast.Compare):
        parts, left = [], node.left
        for op, right in zip(node.ops, node.comparators):
            field = left.id if isinstance(left, ast.Name) and left.id in FIELDS else None
            if isinstance(op, (ast.In, ast.NotIn)):
                if not field or not isinstance(right, (ast.Tuple, ast.List)): raise Err("x in (a, b) needs a field on the left")
                alts = " || ".join(f"f[F_{field.upper()}] == {rhs(field, e)}" for e in right.elts)
                parts.append(f"({alts})" if isinstance(op, ast.In) else f"(!({alts}))")
            else:
                cops = {ast.Eq: "==", ast.NotEq: "!=", ast.Lt: "<", ast.LtE: "<=", ast.Gt: ">", ast.GtE: ">="}
                parts.append(f"({emit(left)} {cops[type(op)]} {rhs(field, right) if field else emit(right)})")
            left = right
        return "(" + " && ".join(parts) + ")"
    if isinstance(node, ast.Call):
        if not isinstance(node.func, ast.Name) or node.func.id not in FUNCS: raise Err(f"unknown function {ast.dump(node.func)}")
        return f"{FUNCS[node.func.id]}(" + ", ".join(f"(float){emit(a)}" for a in node.args) + ")"
    if isinstance(node, ast.Name):
        if node.id in ("true", "True"): return "1"
        if node.id in ("false", "False"): return "0"
        if node.id not in FIELDS: raise Err(f"unknown name {node.id!r}")
        return f"f[F_{node.id.upper()}]"
    if isinstance(node, ast.Constant) and isinstance(node.value, bool): return "1" if node.value else "0"
    if isinstance(node, ast.Constant) and isinstance(node.value, (int, float)):
        return f"{float(node.value)}f" if isinstance(node.value, float) else str(node.value)
    raise Err(f"cannot compile {ast.dump(node)}")

def rhs(field, node):
    """the right side of a comparison with a field: a token name, or a number"""
    if isinstance(node, ast.Name) and node.id not in FIELDS: return value_of(field, node.id)
    if isinstance(node, ast.Constant): return str(node.value)
    return emit(node)

def compile_expr(src):
    src = str(src).replace("true", "True") if str(src).strip() == "true" else str(src)
    return emit(ast.parse(src, mode="eval"))

def main():
    rules = yaml.safe_load(open(os.path.join(ROOT, "model", "teacher_rules.yaml"), encoding="utf-8"))
    out = ["/* GENERATED by tools/gen_rules.py from model/teacher_rules.yaml - do not edit */",
           '#include "brain.h"', "#include <math.h>", "", "/* f[]: the brain state, one value per input field (schema_gen.h F_* / V_*) */"]
    table, habits = [], set()
    for i, r in enumerate(rules):
        try:
            cond, score = compile_expr(r["when"]), compile_expr(r["score"])
            slots = []
            for slot in r["plan"]:
                alts = [a.strip() for a in str(slot).split("|")]
                for a in alts:
                    if a not in ACTS: raise Err(f"unknown action {a!r}")
                slots.append(alts)
            if not 1 <= len(slots) <= 3: raise Err("a plan has 1-3 slots")
            for key, names in (("style", STYLES), ("face", FACES), ("bubble", BUBBLES), ("kind", KINDS)):
                if r[key] not in names: raise Err(f"{key} {r[key]!r} is not one of {names}")
            if not 1 <= int(r["urg"]) <= 9: raise Err("urg is 1..9")
        except (Err, KeyError, SyntaxError) as e:
            sys.exit(f"teacher_rules.yaml: template {r.get('id', i)}: {e}")
        habits.add(r["habit"])
        out += [f"static int  c{i}(const uint8_t *f) {{ return {cond}; }}   /* {r['id']} */",
                f"static float s{i}(const uint8_t *f) {{ return (float)({score}); }}"]
        alt = ", ".join("{ " + ", ".join(f"ACT_{a.upper().replace('ACT_', '')}" for a in s) + " }" for s in slots)
        table.append(f'    {{ "{r["id"]}", "{r["habit"]}", c{i}, s{i}, {{ {alt} }}, {{ {", ".join(str(len(s)) for s in slots)} }}, '
                     f'ST_{r["style"].upper()}, FC_{r["face"].upper()}, BB_{r["bubble"].upper()}, {int(r["urg"])}, {KINDS.index(r["kind"])} }},')
    out += ["", f"const brain_rule_t BRAIN_RULES[{len(rules)}] = {{"] + table + ["};", f"const int BRAIN_N_RULES = {len(rules)};", ""]
    open(os.path.join(ROOT, "common", "lili", "brain_rules_gen.c"), "w", encoding="utf-8", newline="\n").write("\n".join(out))
    missing = sorted({f"H{i}" for i in range(1, 16)} - habits, key=lambda h: int(h[1:]))
    print(f"gen_rules: {len(rules)} templates, habits {len(habits)}/15" + (f" (missing: {', '.join(missing)})" if missing else "") +
          " -> common/lili/brain_rules_gen.c")

if __name__ == "__main__":
    main()
