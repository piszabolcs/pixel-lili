#!/usr/bin/env python3
"""Pixel Lili: the brain's vocabulary from its one source (spec 10.4, M6.1).

    py -3.12 tools/gen_schema.py

model/schema_lili.json -> common/lili/schema_gen.h / .c (the token ids, the input fields' first token and
size, the output slots' classes, the action / style / face / bubble enums and every token's name) and
model/schema_lili.py (the same lists for the Python side: the encoder, the trainer, the visualizer). The ids
are the order of the file: the special tokens, the input fields, then the output classes.
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def expand(spec, name):
    if isinstance(spec, list): return spec
    if "tokens" in spec: return spec["tokens"]
    frm = spec.get("from", 0)
    return [f"{name}_{i}" for i in range(frm, frm + spec["buckets"])]

def main():
    s = json.load(open(os.path.join(ROOT, "model", "schema_lili.json"), encoding="utf-8"))
    tokens = list(s["special"])
    fields = []
    for f in s["input"]:
        t = expand(f, f["field"]); fields.append((f["field"], len(tokens), len(t))); tokens += t
    classes = {}
    acts = [a for g in s["classes"]["act"].values() for a in g]
    classes["act"] = (len(tokens), acts); tokens += acts
    for c in ("st", "fc", "bb", "urg"):
        t = expand(s["classes"][c], c); classes[c] = (len(tokens), t); tokens += t
    assert len(tokens) == len(set(tokens)), "a token twice"
    assert len(tokens) <= s["vocab_size"], f"{len(tokens)} tokens > {s['vocab_size']}"
    up = lambda t: "T_" + t.upper().replace("<", "").replace(">", "").replace("=>", "ARROW")
    names = [up(t) if t != "=>" else "T_ARROW" for t in tokens]
    h = ["/* GENERATED by tools/gen_schema.py from model/schema_lili.json - do not edit */",
         "#ifndef LILI_SCHEMA_GEN_H", "#define LILI_SCHEMA_GEN_H", "#include <stdint.h>", "",
         f"#define SCHEMA_VERSION {s['version']}", f"#define SCHEMA_N_TOKENS {len(tokens)}", f"#define SCHEMA_VOCAB {s['vocab_size']}", "",
         "enum {"] + [f"    {n} = {i}," for i, n in enumerate(names)] + ["};", ""]
    h += ["/* the input fields, in the prompt's order: <bos> F1 .. Fn => (spec 10.3) */", "enum {"] + \
         [f"    F_{n.upper()}," for n, _, _ in fields] + ["    F_COUNT", "};",
         "extern const uint8_t SCHEMA_FIELD_FIRST[F_COUNT], SCHEMA_FIELD_N[F_COUNT];", ""]
    h += ["/* each named input token's index inside its field: the brain state's values (a bucket field's value is its number) */", "enum {"]
    for f in s["input"]:
        if "tokens" in f:
            h += [f"    V_{t.upper()} = {i}," for i, t in enumerate(f["tokens"])]
    h += ["};", ""]
    first_act = classes["act"][0]
    h += ["/* the brain's actions (spec 10.4; the rug instead of the bed: docs/decisions.md) */", "typedef enum {"] + \
         [f"    ACT_{a.upper().replace('ACT_', '')}," for a in acts] + ["    ACT_COUNT", "} action_t;",
         f"#define ACT_TOKEN(a) ((uint8_t)({first_act} + (a)))"]
    for c, enum_name, prefix in (("st", "style_t", "ST_"), ("fc", "face_t", "FC_"), ("bb", "bubble_t", "BB_")):
        f0, t = classes[c]
        h += ["typedef enum {"] + [f"    {prefix}{x.split('_', 1)[1].upper()}," for x in t] + [f"    {prefix}COUNT", f"}} {enum_name};",
              f"#define {prefix}TOKEN(x) ((uint8_t)({f0} + (x)))"]
    h += [f"#define URG_TOKEN(u) ((uint8_t)({classes['urg'][0]} + (u) - 1))   /* u = 1..9 */", "",
          "/* the output slots and the class each takes (constrained decoding, spec 10.5) */",
          "enum { SLOT_A1, SLOT_A2, SLOT_A3, SLOT_STYLE, SLOT_FACE, SLOT_BUBBLE, SLOT_URG, SLOT_COUNT };",
          "extern const uint8_t SCHEMA_SLOT_FIRST[SLOT_COUNT], SCHEMA_SLOT_N[SLOT_COUNT];",
          "extern const char *const SCHEMA_TOKENS[SCHEMA_N_TOKENS];",
          "#define ACTION_NAME(a) (SCHEMA_TOKENS[ACT_TOKEN(a)])", "", "#endif"]
    slot_cls = [s2["class"] for s2 in s["output"]]
    c = ["/* GENERATED by tools/gen_schema.py from model/schema_lili.json - do not edit */", '#include "schema_gen.h"', "",
         "const uint8_t SCHEMA_FIELD_FIRST[F_COUNT] = { " + ", ".join(str(f) for _, f, _ in fields) + " };",
         "const uint8_t SCHEMA_FIELD_N[F_COUNT] = { " + ", ".join(str(n) for _, _, n in fields) + " };",
         "const uint8_t SCHEMA_SLOT_FIRST[SLOT_COUNT] = { " + ", ".join(str(classes[k][0]) for k in slot_cls) + " };",
         "const uint8_t SCHEMA_SLOT_N[SLOT_COUNT] = { " + ", ".join(str(len(classes[k][1])) for k in slot_cls) + " };",
         "const char *const SCHEMA_TOKENS[SCHEMA_N_TOKENS] = {"] + [f'    "{t}",' for t in tokens] + ["};"]
    out = os.path.join(ROOT, "common", "lili")
    open(os.path.join(out, "schema_gen.h"), "w", encoding="utf-8", newline="\n").write("\n".join(h) + "\n")
    open(os.path.join(out, "schema_gen.c"), "w", encoding="utf-8", newline="\n").write("\n".join(c) + "\n")
    py = ['"""GENERATED by tools/gen_schema.py from model/schema_lili.json - do not edit. Pixel Lili\'s brain vocabulary."""',
          f"VERSION = {s['version']}", f"VOCAB = {s['vocab_size']}",
          f"TOKENS = {json.dumps(tokens, ensure_ascii=False)}",
          "ID = {t: i for i, t in enumerate(TOKENS)}",
          f"FIELDS = {json.dumps([(n, f, k) for n, f, k in fields])}   # (name, first id, how many)",
          f"SLOTS = {json.dumps([(s2['slot'], classes[s2['class']][0], len(classes[s2['class']][1])) for s2 in s['output']])}",
          f"ACTIONS = {json.dumps(acts)}",
          "",
          "def encode(state):",
          '    """state: {field: token or bucket number} -> the prompt ids: <bos> F1 .. Fn =>"""',
          "    ids = [ID['<bos>']]",
          "    for name, first, n in FIELDS:",
          "        v = state[name]",
          "        ids.append(first + min(max(int(v), 0), n - 1) if isinstance(v, (int, float)) else ID[v])",
          "    return ids + [ID['=>']]",
          "",
          "def decode(ids):",
          "    return [TOKENS[i] for i in ids]", ""]
    open(os.path.join(ROOT, "model", "schema_lili.py"), "w", encoding="utf-8", newline="\n").write("\n".join(py))
    print(f"gen_schema: {len(tokens)} tokens ({len(fields)} input fields, {len(acts)} actions) of {s['vocab_size']} "
          "-> common/lili/schema_gen.[ch], model/schema_lili.py")

if __name__ == "__main__":
    main()
