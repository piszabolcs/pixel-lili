#!/usr/bin/env python3
"""Pixel Lili: compile assets/maps/*.json into C tables (common/lili/maps_gen.h / .c).

    python3 tools/gen_maps.py           (the simulator's make runs it when a map changes)

Why a generator: the device should not parse JSON (code, RAM, failure modes); the
JSON stays the one editable source, the C is a build product - never edit it by hand
(the same rule as the schema's vocab.h, CLAUDE.md 9).

The walkable grid: a 4 x 4 px cell is walkable when its centre is inside the floor
polygon and outside every blocked rect / circle. Points of every map share one id
space (SPOT_*); a point absent from a map has z = -1 there. Prop sort_y = the
prop's front edge (y + h), the key the Y-sort draws by (spec 8.5).
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAPS = ["room", "yard"]                     # view order: VIEW_ROOM = 0, VIEW_YARD = 1
RAMPS = ["floor", "wall", "grass", "hedge", "fur", "fur_w", "wood", "blanket", "metal",
         "water", "pad", "house", "flower", "leaf", "rug_green", "rug_gray"]
CELL = 4
def logical_w():
    """LILI_LOG_W from config.h: the maps are written on a 240 grid and scaled by LILI_K (2 at native 480)"""
    c = open(os.path.join(ROOT, "common", "lili", "config.h"), encoding="utf-8").read()
    phys = int(re.search(r"LILI_PHYS_W\s+(\d+)", c).group(1)); scale = int(re.search(r"LILI_SCALE\s+(\d+)", c).group(1))
    return phys // scale
LOG = logical_w(); K = LOG // 240; GW = GH = LOG // CELL

def scaled(m):
    """every coordinate and size of a map x K (depth and height too); the JSON stays on the design grid"""
    m = json.loads(json.dumps(m))
    m["floor"] = [[x * K, y * K] for x, y in m["floor"]]
    for b in m.get("blocked", []):
        if "rect" in b: b["rect"] = [v * K for v in b["rect"]]
        else: b["circle"] = [v * K for v in b["circle"]]
    m["points"] = {k: [v[0] * K, v[1] * K, v[2] * K if v[2] >= 0 else v[2]] for k, v in m["points"].items()}
    for p in m["props"]:
        p["rect"] = [v * K for v in p["rect"]]
        if "height" in p: p["height"] = p["height"] * K
    for z in m.get("zones", {}).values():
        if "rect" in z: z["rect"] = [v * K for v in z["rect"]]
        else: z["poly"] = [[x * K, y * K] for x, y in z["poly"]]
    m["background"]["wall_bottom"] = m["background"]["wall_bottom"] * K
    return m
PATTERNS = {"": 0, "rug": 1}               # how a prop is drawn: 0 a plain box, 1 the rug's triangles

def inside_poly(x, y, poly):
    """even-odd ray casting"""
    c = False
    for i in range(len(poly)):
        x1, y1 = poly[i]; x2, y2 = poly[(i + 1) % len(poly)]
        if (y1 > y) != (y2 > y) and x < (x2 - x1) * (y - y1) / (y2 - y1) + x1:
            c = not c
    return c

def blocked(x, y, blocks):
    for b in blocks:
        if "rect" in b:
            bx, by, bw, bh = b["rect"]
            if bx <= x < bx + bw and by <= y < by + bh: return True
        else:
            cx, cy, r = b["circle"]
            if (x - cx) ** 2 + (y - cy) ** 2 <= r * r: return True
    return False

def spot_id(s):                              # "spot_center" -> SPOT_CENTER, "bowl_food" -> SPOT_BOWL_FOOD
    return "SPOT_" + (s[5:] if s.startswith("spot_") else s).upper()

def main():
    maps = [scaled(json.load(open(os.path.join(ROOT, "assets", "maps", f"{n}.json"), encoding="utf-8"))) for n in MAPS]
    spots = sorted({p for m in maps for p in m["points"]})
    h, c = [], []
    h += ["/* GENERATED by tools/gen_maps.py from assets/maps/<name>.json - do not edit */",
          "#ifndef LILI_MAPS_GEN_H", "#define LILI_MAPS_GEN_H", '#include "map.h"', ""]
    h += ["enum {"] + [f"    {spot_id(s)}," for s in spots] + ["    SPOT_COUNT", "};"]
    h += ["enum {"] + [f"    RAMP_ID_{r.upper()}," for r in RAMPS] + ["    RAMP_ID_COUNT", "};"]
    h += [f"extern const map_t MAPS[{len(maps)}];", "extern const char *const SPOT_NAMES[SPOT_COUNT];   /* the JSON's names, for tests and logs */", "", "#endif"]
    c += ["/* GENERATED by tools/gen_maps.py from assets/maps/<name>.json - do not edit */",
          '#include "maps_gen.h"', ""]
    c += ["const char *const SPOT_NAMES[SPOT_COUNT] = {"] + [f'    [{spot_id(s)}] = "{s}",' for s in spots] + ["};", ""]
    for m in maps:
        n = m["name"]
        walk = bytearray((GW * GH + 7) // 8); count = 0
        for gy in range(GH):
            for gx in range(GW):
                x, y = gx * CELL + CELL / 2, gy * CELL + CELL / 2
                if inside_poly(x, y, m["floor"]) and not blocked(x, y, m["blocked"]):
                    i = gy * GW + gx; walk[i >> 3] |= 1 << (i & 7); count += 1
        c.append(f"static const uint8_t walk_{n}[{len(walk)}] = {{  /* {count} of {GW * GH} cells walkable */")
        for i in range(0, len(walk), 25): c.append("    " + ", ".join(f"0x{b:02x}" for b in walk[i:i + 25]) + ",")
        c.append("};")
        c.append(f"static const map_point_t pts_{n}[SPOT_COUNT] = {{")
        for s in spots:
            x, y, z = m["points"].get(s, [0, 0, -1])
            c.append(f"    [{spot_id(s)}] = {{ {x}, {y}, {z} }},")
        c.append("};")
        c.append(f"static const map_prop_t props_{n}[] = {{")
        for p in sorted(m["props"], key=lambda p: (not p.get("flat", False), p["rect"][1] + p["rect"][3])):
            x, y, w, hh = p["rect"]
            c.append(f'    {{ "{p["id"]}", {x}, {y}, {w}, {hh}, RAMP_ID_{p["ramp"].upper()}, {p.get("height", 0)}, '
                     f'{1 if p.get("flat") else 0}, {y + hh}, {PATTERNS[p.get("pattern", "")]} }},')
        c.append("};")
        zl = []
        for zid, z in m.get("zones", {}).items():
            if "rect" in z:
                zl.append(f'    {{ "{zid}", 0, {", ".join(map(str, z["rect"]))}, 0, 0 }},')
            else:
                flat = [v for pt in z["poly"] for v in pt]
                c.append(f"static const int16_t poly_{n}_{zid}[] = {{ {', '.join(map(str, flat))} }};")
                zl.append(f'    {{ "{zid}", 1, 0, 0, 0, 0, poly_{n}_{zid}, {len(z["poly"])} }},')
        c.append(f"static const map_zone_t zones_{n}[] = {{"); c += zl; c.append("};")
        c.append("")
    c.append(f"const map_t MAPS[{len(maps)}] = {{")
    for m in maps:
        n, bg = m["name"], m["background"]
        c.append(f'    {{ "{n}", RAMP_ID_{bg["floor_ramp"].upper()}, RAMP_ID_{bg["wall_ramp"].upper()}, {bg["wall_bottom"]}, '
                 f'walk_{n}, pts_{n}, props_{n}, {len(m["props"])}, zones_{n}, {len(m.get("zones", {}))} }},')
    c.append("};")
    out = os.path.join(ROOT, "common", "lili")
    open(os.path.join(out, "maps_gen.h"), "w", encoding="utf-8", newline="\n").write("\n".join(h) + "\n")
    open(os.path.join(out, "maps_gen.c"), "w", encoding="utf-8", newline="\n").write("\n".join(c) + "\n")
    print(f"gen_maps: {len(maps)} maps, {len(spots)} spots -> common/lili/maps_gen.[ch]")

if __name__ == "__main__":
    sys.exit(main())
