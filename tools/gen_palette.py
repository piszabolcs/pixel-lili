#!/usr/bin/env python3
"""Pixel Lili: assets/palettes/master.json -> common/lili/palette_gen.c (the master palette the core
boots with; the pak carries the same bytes as its PALETTE entry). Run by tools/build_assets.py."""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def main():
    m = json.load(open(os.path.join(ROOT, "assets", "palettes", "master.json"), encoding="utf-8"))
    rgb = m["rgb"]
    assert len(rgb) == 256
    lines = ["/* GENERATED by tools/gen_palette.py from assets/palettes/master.json (tools/palette_from_photos.py) - do not edit */",
             '#include "palette.h"', "", "const uint8_t PAL_MASTER[256][3] = {"]
    for i in range(0, 256, 8):
        lines.append("    " + " ".join("{%3d,%3d,%3d}," % tuple(rgb[j]) for j in range(i, i + 8)) + f"   /* {i} */")
    lines += ["};", ""]
    open(os.path.join(ROOT, "common", "lili", "palette_gen.c"), "w", encoding="utf-8", newline="\n").write("\n".join(lines))
    print("palette_gen.c: 256 colours")
if __name__ == "__main__":
    main()
